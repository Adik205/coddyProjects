package coddy

func numDecodings(s string) int {
    dp := make([]int, len(s)+1)
    dp[0] = 1 // 1 вариант, когда ничего не расшифруем

    if s[0] == '0' { // Когда цифра только одна
        dp[1] = 0 // Если 0, то и вариантов нет
    } else {
        dp[1] = 1 // Если не 0, то можно построить 1 вариант
    }

    for i := 2; i <= len(s); i++ {
        dp[i] = 0
        if s[i-1] >= '1' && s[i-1] <= '9' { // Если последняя цифра между 1 и 9
            dp[i] += dp[i-1] // То добавляем кол-во вариантов у строки с первыми i - 1 цифрами, ведь к тем вариантам просто добавлю i-шную цифру
        }
        if s[i-2] == '1' || s[i-2] == '2' && s[i-1] >= '0' && s[i-1] <= '6' { // Если последние 2 цифры находится между 10 и 26
            dp[i] += dp[i-2] // То добавляем кол-во вариантов у строки с первыми i - 2 цифрами, ведь к тем вариантам просто добавлю последние 2 цифры текущего варианта
        }
    }
    return dp[len(s)]
}